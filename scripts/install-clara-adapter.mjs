#!/usr/bin/env node
// Install the Clara strict enforcement adapter for OpenCode.
//
//   pnpm clara adapter install opencode
//   pnpm clara adapter uninstall
//   pnpm clara adapter status
//
// The adapter also installs the human-facing Clara agent. The agent is the
// entry point; the manual /pipeline command belongs to the MCP-only path.

import {
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  readlinkSync,
  rmSync,
  symlinkSync,
  unlinkSync,
} from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { removeGeneratedCommand } from './lib/clara-command.mjs'
import {
  agentHash,
  installAgentFile,
  readAgentManifest,
  removeAgentFile,
} from './lib/opencode-agent.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pluginDir = join(root, 'plugins', 'clara-policy')
const configHome = process.env.XDG_CONFIG_HOME?.trim() || join(homedir(), '.config')
const pluginsDir = join(configHome, 'opencode', 'plugins')
const agentsDir = join(configHome, 'opencode', 'agents')
const link = join(pluginsDir, 'clara-policy')
const agentSource = join(pluginDir, 'agents', 'clara.md')
const agentDestination = join(agentsDir, 'clara.md')
const agentManifest = join(agentsDir, '.clara-policy-agents.json')
const force = process.argv.includes('--force')
const command = process.argv[2] ?? 'install'
const target = process.argv[3]

if (command === 'help' || command === '--help' || command === '-h') {
  console.log(
    'Clara OpenCode adapter\n\nUsage: pnpm clara adapter <install|uninstall|status> [opencode]'
  )
} else if (command === 'install') install(target)
else if (command === 'uninstall') uninstall()
else if (command === 'status') status()
else fail(`unknown command: ${command}`)

function install(target) {
  if (target && target !== 'opencode') fail(`unsupported adapter: ${target}`)
  if (!existsSync(join(pluginDir, 'index.ts'))) fail(`plugin not found at ${pluginDir}`)
  if (!existsSync(agentSource)) fail(`agent definition not found at ${agentSource}`)

  linkAdapter()
  installAgent()
  removeAdapterCommand()

  console.log('')
  console.log('Clara agent: select "clara" in OpenCode.')
  console.log('Reload OpenCode with `opencode reload`, or restart the service.')
}

function linkAdapter() {
  mkdirSync(pluginsDir, { recursive: true, mode: 0o700 })
  const existing = lstatSafe(link)
  if (existing?.isSymbolicLink()) {
    const current = resolve(pluginsDir, readlinkSync(link))
    if (current === pluginDir) {
      console.log(`ok   adapter link ${link}`)
      return
    }
    unlinkSync(link)
  } else if (existing) {
    if (!force) fail(`${link} exists and is not a symlink; re-run with --force`)
    rmSync(link, { recursive: true, force: true })
  }
  symlinkSync(pluginDir, link, 'dir')
  console.log(`link adapter ${link} -> ${pluginDir}`)
}

function installAgent() {
  try {
    const installed = installAgentFile({
      id: 'clara',
      source: agentSource,
      destination: agentDestination,
      manifestPath: agentManifest,
      force,
    })
    console.log(`${installed.written ? 'write' : 'ok   '} agent ${installed.path}`)
  } catch (error) {
    fail(error instanceof Error ? error.message : String(error))
  }
}

function removeAdapterCommand() {
  const removed = removeGeneratedCommand()
  if (removed.removed) console.log(`removed /pipeline command ${removed.path}`)
  else if (removed.kept) console.log(`keep ${removed.path} (not generated by this installer)`)
}

function uninstall() {
  const existing = lstatSafe(link)
  if (!existing) {
    console.log('adapter is not installed')
    return
  }
  if (existing.isSymbolicLink()) unlinkSync(link)
  else rmSync(link, { recursive: true, force: true })
  console.log(`removed ${link}`)

  const agent = removeAgentFile({
    id: 'clara',
    destination: agentDestination,
    manifestPath: agentManifest,
  })
  if (agent.removed) console.log(`removed agent ${agent.path}`)
  else if (agent.kept) console.log(`keep modified agent ${agent.path}`)

  if (!mcpEntryConfigured()) {
    const command = removeGeneratedCommand()
    if (command.removed) console.log(`removed /pipeline command ${command.path}`)
  }
}

function status() {
  console.log(`adapter: ${existsSync(link) ? 'installed' : 'missing'}`)
  console.log(`path: ${link}`)
  console.log(`plugin: ${pluginDir}`)
  console.log(`agent: ${agentStatus()}`)
  console.log(`agent path: ${agentDestination}`)
  console.log(
    `/pipeline command: ${
      existsSync(join(configHome, 'opencode', 'commands', 'pipeline.md'))
        ? 'installed (manual MCP mode)'
        : 'missing'
    }`
  )
}

function agentStatus() {
  if (!existsSync(agentDestination)) return 'missing'
  const manifest = readAgentManifest(agentManifest)
  const content = readFileSync(agentDestination, 'utf8')
  return manifest.agents.clara === agentHash(content) ? 'installed' : 'modified'
}

function mcpEntryConfigured() {
  const configPath = join(configHome, 'opencode', 'opencode.json')
  if (!existsSync(configPath)) return false
  try {
    const config = JSON.parse(readFileSync(configPath, 'utf8'))
    return Boolean(config && config.mcp && config.mcp.clara)
  } catch {
    return false
  }
}

function lstatSafe(path) {
  try {
    return lstatSync(path)
  } catch {
    return undefined
  }
}

function fail(message) {
  console.error(`error ${message}`)
  process.exit(1)
}
