// Install and remove a single generated OpenCode agent file.
//
// Clara's installers must never overwrite a file a human authored. The manifest
// records the hash of every file this installer wrote.

import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs'
import { dirname } from 'node:path'

export function agentHash(value) {
  return createHash('sha256').update(value).digest('hex')
}

export function readAgentManifest(path) {
  if (!existsSync(path)) return { agents: {} }
  try {
    const parsed = JSON.parse(readFileSync(path, 'utf8'))
    return {
      agents:
        parsed && typeof parsed.agents === 'object' && parsed.agents !== null ? parsed.agents : {},
    }
  } catch {
    return { agents: {} }
  }
}

function writeAgentManifest(path, manifest) {
  mkdirSync(dirname(path), { recursive: true, mode: 0o700 })
  writeFileSync(path, `${JSON.stringify({ agents: manifest.agents }, null, 2)}\n`, { mode: 0o600 })
}

export function installAgentFile({ id, source, destination, manifestPath, force = false }) {
  if (!/^[A-Za-z0-9_-]+$/.test(id)) throw new Error(`Agent id "${id}" is not a safe file name`)

  const content = readFileSync(source, 'utf8')
  const manifest = readAgentManifest(manifestPath)
  const existing = existsSync(destination) ? readFileSync(destination, 'utf8') : undefined

  if (existing !== undefined && existing !== content) {
    const unchangedSinceInstall = manifest.agents[id] === agentHash(existing)
    if (!unchangedSinceInstall && !force) {
      throw new Error(
        `Refusing to overwrite ${destination}: it was not generated by this installer. ` +
          'Re-run with --force to replace it.'
      )
    }
  }

  mkdirSync(dirname(destination), { recursive: true, mode: 0o700 })
  if (existing !== content) writeFileSync(destination, content, { mode: 0o600 })
  manifest.agents[id] = agentHash(content)
  writeAgentManifest(manifestPath, manifest)

  return { path: destination, written: existing !== content }
}

export function removeAgentFile({ id, destination, manifestPath }) {
  const manifest = readAgentManifest(manifestPath)
  if (!existsSync(destination)) {
    delete manifest.agents[id]
    writeAgentManifest(manifestPath, manifest)
    return { path: destination, removed: false, kept: false }
  }

  const existing = readFileSync(destination, 'utf8')
  if (manifest.agents[id] !== agentHash(existing)) {
    return { path: destination, removed: false, kept: true }
  }

  unlinkSync(destination)
  delete manifest.agents[id]
  writeAgentManifest(manifestPath, manifest)
  return { path: destination, removed: true, kept: false }
}
