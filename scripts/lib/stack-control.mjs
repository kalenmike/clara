export function envPath(repoRoot = root) {
  return join(repoRoot, 'docker', '.env')
}

export function parseSelection(args, { build = true, json = false } = {}) {
  const selection = {
    server: true,
    web: true,
    orchestrator: true,
    build: false,
    json: false,
    mode: 'docker',
  }
  let local = false
  let docker = false
  for (const arg of args) {
    if (arg === '--no-server') selection.server = false
    else if (arg === '--no-web') selection.web = false
    else if (arg === '--no-orchestrator') selection.orchestrator = false
    else if (arg === '--build' && build) selection.build = true
    else if (arg === '--json' && json) selection.json = true
    else if (arg === '--local') local = true
    else if (arg === '--docker') docker = true
    else throw new Error(`unknown option: ${arg}`)
  }
  if (local && docker) throw new Error('--local and --docker cannot be combined')
  selection.mode = local ? 'local' : 'docker'
  return selection
}

export function selectedNames(selection, order = SERVICES) {
  return order.filter((name) => selection[name])
}

export function dataHome() {
  return process.env.XDG_DATA_HOME?.trim() || join(homedir(), '.local', 'share')
}

/** Docker-only host state. Local installs never read or write this directory. */
export function dockerStateDir(env = process.env) {
  const configured = env.CLARA_DOCKER_STATE_DIR?.trim()
  return configured ? resolve(expandHome(configured)) : join(dataHome(), 'clara', 'docker')
}

export function dockerTokenPath(env = process.env) {
  return join(dockerStateDir(env), 'orchestrator.token')
}

export function defaultEnv(repoRoot = root) {
  return {
    CLARA_ORCHESTRATION_TOKEN: randomBytes(32).toString('hex'),
    CLARA_WORKSPACE: resolve(repoRoot),
  }
}

/** Read the simple KEY=value form used by docker/.env. */
export function parseEnvFile(path) {
  const values = {}
  for (const line of readFileSync(path, 'utf8').split(/\r?\n/)) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith('#')) continue
    const index = trimmed.indexOf('=')
    if (index <= 0) continue
    const key = trimmed.slice(0, index).trim()
    let value = trimmed.slice(index + 1).trim()
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1)
    }
    if (key) values[key] = value
  }
  return values
}

function writeEnvFile(path, values) {
  mkdirSync(dirname(path), { recursive: true, mode: 0o700 })
  const lines = [
    '# Generated by `pnpm clara start` on first run.',
    '# Keep this file private. It holds the orchestrator bearer token.',
    '',
    ...Object.entries(values).map(([key, value]) => `${key}=${value}`),
    '',
  ]
  writeFileSync(path, lines.join('\n'), { mode: 0o600 })
}

function expandHome(value) {
  if (value === '~') return homedir()
  if (value.startsWith('~/')) return join(homedir(), value.slice(2))
  return value
}

function readText(path) {
  try {
    return readFileSync(path, 'utf8').trim()
  } catch {
    return ''
  }
}

/** The orchestrator token from the Docker stack, independent of local state. */
export function readDockerToken(repoRoot = root, env = process.env) {
  const path = envPath(repoRoot)
  if (existsSync(path)) {
    const token = parseEnvFile(path).CLARA_ORCHESTRATION_TOKEN?.trim()
    if (token) return token
  }
  return readText(dockerTokenPath(env))
}

export function orchestratorContainerRunning() {
  const result = spawnSync(
    'docker',
    ['inspect', '--format', '{{.State.Running}}', CONTAINERS.orchestrator],
    { encoding: 'utf8', timeout: 3_000 }
  )
  if (result.error || result.status !== 0) return false
  return result.stdout.trim() === 'true'
}

/**
 * Ensure the orchestrator's compose variables exist, validate host paths, and
 * keep the Docker control token in the Docker-only state directory.
 */
export function ensureOrchestratorEnv(repoRoot = root) {
  const path = envPath(repoRoot)
  let values
  if (existsSync(path)) {
    values = parseEnvFile(path)
  } else {
    values = defaultEnv(repoRoot)
    writeEnvFile(path, values)
    console.log(`created ${path}`)
  }

  const missing = ['CLARA_ORCHESTRATION_TOKEN', 'CLARA_WORKSPACE'].filter(
    (key) => !values[key]?.trim()
  )
  if (missing.length) {
    throw new Error(
      `${path} is missing ${missing.join(', ')}. Copy docker/.env.example or remove the file so \`pnpm clara start\` can create it.`
    )
  }
  if (values.CLARA_ORCHESTRATION_TOKEN === 'replace-with-a-long-random-token') {
    throw new Error(
      `${path} still has the example token. Generate one with \`openssl rand -hex 32\`.`
    )
  }

  const workspace = expandHome(values.CLARA_WORKSPACE)
  if (!isAbsolute(workspace)) {
    throw new Error(`CLARA_WORKSPACE must be an absolute path: ${workspace}`)
  }
  if (!existsSync(workspace)) {
    throw new Error(`CLARA_WORKSPACE does not exist: ${workspace}`)
  }

  for (const key of [
    'CLARA_SERVER_CONFIG_DIR',
    'CLARA_SERVER_DATA_DIR',
    'CLARA_ORCHESTRATOR_DATA_DIR',
  ]) {
    const value = values[key]?.trim()
    if (!value) continue
    const expanded = expandHome(value)
    if (!isAbsolute(expanded)) {
      throw new Error(`${key} must be an absolute path when set: ${expanded}`)
    }
  }

  const stateDir = dockerStateDir()
  mkdirSync(stateDir, { recursive: true, mode: 0o700 })
  const tokenPath = dockerTokenPath()
  const previous = readText(tokenPath)
  if (previous !== values.CLARA_ORCHESTRATION_TOKEN) {
    writeFileSync(tokenPath, `${values.CLARA_ORCHESTRATION_TOKEN}\n`, { mode: 0o600 })
    console.log(`wrote ${tokenPath}`)
  }

  return { path, tokenPath, workspace, stateDir }
}

export function orchestratorURL(env = process.env) {
  const port = Number.parseInt(String(env.CLARA_ORCHESTRATION_PORT ?? '8789'), 10)
  return `http://127.0.0.1:${Number.isInteger(port) && port > 0 ? port : 8789}`
}
