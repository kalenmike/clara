#!/usr/bin/env node
// Link the Clara ledger plugin into OpenCode and render its agents.
//
// The plugin itself is a local plugin directory. OpenCode cannot register new
// agents from plugin code, so the agent definitions live in agents.json and
// this script turns them into the markdown files OpenCode discovers.

import { createHash } from 'node:crypto'
import {
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  readlinkSync,
  rmSync,
  symlinkSync,
  unlinkSync,
  writeFileSync,
} from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pluginDir = join(root, 'plugins', 'clara')
const agentsFile = join(pluginDir, 'agents.json')
const force = process.argv.includes('--force')

const configHome = process.env.XDG_CONFIG_HOME?.trim() || join(homedir(), '.config')
const opencodeDir = join(configHome, 'opencode')
const pluginsDir = join(opencodeDir, 'plugins')
const agentsDir = join(opencodeDir, 'agents')
const claraDir = process.env.CLARA_CONFIG_DIR?.trim() || join(configHome, 'clara')

const pluginLink = join(pluginsDir, 'clara')
const agentManifest = join(agentsDir, '.clara-agents.json')
const management = await readManagement()

if (!existsSync(join(pluginDir, 'index.ts'))) {
  fail(`Plugin entry not found at ${join(pluginDir, 'index.ts')}`)
}
if (!existsSync(agentsFile)) {
  fail(`Agent definitions not found at ${agentsFile}`)
}

mkdirSync(pluginsDir, { recursive: true, mode: 0o700 })
mkdirSync(agentsDir, { recursive: true, mode: 0o700 })
mkdirSync(claraDir, { recursive: true, mode: 0o700 })

linkPlugin()
installAgents()

const ledger = join(claraDir, 'ledger.db')
console.log(`\nLedger: ${ledger}`)
console.log(`Settings DB left untouched: ${join(claraDir, 'clara.db')}`)
console.log(
  management
    ? 'Clara management: on'
    : 'Clara management: off (agents are rendered disabled; enable it in the panel)'
)
console.log('Reload OpenCode with `opencode reload`, or restart the service.')

function linkPlugin() {
  const existing = lstatSafe(pluginLink)
  if (existing?.isSymbolicLink()) {
    const current = resolve(pluginsDir, readlinkSync(pluginLink))
    if (current === pluginDir) {
      console.log(`ok   plugin link ${pluginLink}`)
      return
    }
    unlinkSync(pluginLink)
  } else if (existing) {
    if (!force) {
      fail(`${pluginLink} exists and is not a symlink. Re-run with --force to replace it.`)
    }
    rmSync(pluginLink, { recursive: true, force: true })
  }

  symlinkSync(pluginDir, pluginLink, 'dir')
  console.log(`link plugin ${pluginLink} -> ${pluginDir}`)
}

function installAgents() {
  const definitions = JSON.parse(readFileSync(agentsFile, 'utf8'))
  if (!definitions || typeof definitions.agents !== 'object' || definitions.agents === null) {
    fail(`${agentsFile} must contain an "agents" object`)
  }

  const manifest = readManifest()
  const next = { ...manifest.agents }
  const conflicts = []
  let written = 0

  for (const [id, definition] of Object.entries(definitions.agents)) {
    if (!/^[A-Za-z0-9_-]+$/.test(id)) {
      fail(`Agent id "${id}" is not a safe file name`)
    }
    if (!definition || typeof definition !== 'object') {
      fail(`Agent "${id}" must be an object`)
    }

    const content = renderAgent(definition, management)
    const path = join(agentsDir, `${id}.md`)
    const existing = existsSync(path) ? readFileSync(path, 'utf8') : undefined
    const previousHash = manifest.agents[id]

    if (existing !== undefined && existing !== content) {
      const unchangedSinceInstall = previousHash === hash(existing)
      if (!force && !unchangedSinceInstall) {
        conflicts.push(path)
        continue
      }
    }

    if (existing !== content) {
      writeFileSync(path, content, { mode: 0o600 })
      written++
      console.log(`write agent ${path}`)
    }
    next[id] = hash(content)
  }

  if (conflicts.length > 0) {
    fail(
      `Refusing to overwrite agent files that were not generated by this install:\n` +
        conflicts.map((file) => `  ${file}`).join('\n') +
        '\nRe-run with --force if you want to replace them.'
    )
  }

  writeFileSync(agentManifest, `${JSON.stringify({ agents: next }, null, 2)}\n`, { mode: 0o600 })
  console.log(`ok   agents ${Object.keys(definitions.agents).join(', ')} (${written} updated)`)
}

function readManifest() {
  if (!existsSync(agentManifest)) return { agents: {} }
  try {
    const parsed = JSON.parse(readFileSync(agentManifest, 'utf8'))
    return { agents: parsed && typeof parsed.agents === 'object' ? parsed.agents : {} }
  } catch {
    return { agents: {} }
  }
}

function renderAgent(agent, enabled) {
  const { system, ...frontmatter } = agent
  if (typeof frontmatter.description !== 'string') {
    fail('Every agent needs a description')
  }
  const yaml = renderYaml(enabled ? frontmatter : { ...frontmatter, disabled: true }, 0)
  const body = typeof system === 'string' ? system.trim() : ''
  return `---\n${yaml}\n---\n\n${body}\n`
}

/** The panel owns the master switch; the installer only reads it. */
async function readManagement() {
  const path = join(claraDir, 'clara.db')
  if (!existsSync(path)) return false

  try {
    const { DatabaseSync } = await import('node:sqlite')
    const db = new DatabaseSync(path)
    try {
      const row = db.prepare('SELECT value FROM settings WHERE key = ?').get('management.enabled')
      if (!row || typeof row.value !== 'string') return false
      return JSON.parse(row.value) === true
    } finally {
      db.close()
    }
  } catch {
    return false
  }
}

// Small YAML emitter for the config shapes used by agents.json. Strings are
// JSON-quoted so values such as "*" and "docs/features/**" stay unambiguous.
function renderYaml(value, indent) {
  const pad = ' '.repeat(indent)

  if (Array.isArray(value)) {
    if (value.length === 0) return `${pad}[]`
    return value
      .map((item) => {
        if (item && typeof item === 'object' && !Array.isArray(item)) {
          const entries = Object.entries(item)
          const [first, ...rest] = entries
          let out = `${pad}- ${first[0]}: ${scalar(first[1])}`
          for (const [key, child] of rest) {
            out += `\n${pad}  ${key}: ${scalar(child)}`
          }
          return out
        }
        return `${pad}- ${scalar(item)}`
      })
      .join('\n')
  }

  if (value && typeof value === 'object') {
    const entries = Object.entries(value)
    if (entries.length === 0) return `${pad}{}`
    return entries
      .map(([key, child]) => {
        if (child && typeof child === 'object') {
          return `${pad}${key}:\n${renderYaml(child, indent + 2)}`
        }
        return `${pad}${key}: ${scalar(child)}`
      })
      .join('\n')
  }

  return `${pad}${scalar(value)}`
}

function scalar(value) {
  if (typeof value === 'string') return JSON.stringify(value)
  if (typeof value === 'number' || typeof value === 'boolean') return String(value)
  if (value === null) return 'null'
  fail(`Cannot render ${typeof value} in agent frontmatter`)
}

function hash(value) {
  return createHash('sha256').update(value).digest('hex')
}

function lstatSafe(path) {
  try {
    return lstatSync(path)
  } catch {
    return undefined
  }
}

function fail(message) {
  console.error(`error ${message}`)
  process.exit(1)
}
