import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs'
import { dirname } from 'node:path'

export function agentHash(value: string): string {
  return createHash('sha256').update(value).digest('hex')
}

interface AgentManifest {
  agents: Record<string, string>
}

export function readAgentManifest(path: string): AgentManifest {
  if (!existsSync(path)) return { agents: {} }
  try {
    const parsed = JSON.parse(readFileSync(path, 'utf8')) as { agents?: unknown }
    return {
      agents:
        parsed && typeof parsed.agents === 'object' && parsed.agents !== null
          ? (parsed.agents as Record<string, string>)
          : {},
    }
  } catch {
    return { agents: {} }
  }
}

function writeAgentManifest(path: string, manifest: AgentManifest): void {
  mkdirSync(dirname(path), { recursive: true, mode: 0o700 })
  writeFileSync(path, `${JSON.stringify({ agents: manifest.agents }, null, 2)}\n`, {
    mode: 0o600,
  })
}

export function installAgentFile(input: {
  id: string
  source: string
  destination: string
  manifestPath: string
  force?: boolean
}): { path: string; written: boolean } {
  if (!/^[A-Za-z0-9_-]+$/.test(input.id)) {
    throw new Error(`Agent id "${input.id}" is not a safe file name`)
  }
  const content = readFileSync(input.source, 'utf8')
  const manifest = readAgentManifest(input.manifestPath)
  const existing = existsSync(input.destination)
    ? readFileSync(input.destination, 'utf8')
    : undefined

  if (existing !== undefined && existing !== content) {
    const unchangedSinceInstall = manifest.agents[input.id] === agentHash(existing)
    if (!unchangedSinceInstall && !input.force) {
      throw new Error(
        `Refusing to overwrite ${input.destination}: it was not generated by this installer. ` +
          'Re-run with --force to replace it.'
      )
    }
  }

  mkdirSync(dirname(input.destination), { recursive: true, mode: 0o700 })
  if (existing !== content) writeFileSync(input.destination, content, { mode: 0o600 })
  manifest.agents[input.id] = agentHash(content)
  writeAgentManifest(input.manifestPath, manifest)
  return { path: input.destination, written: existing !== content }
}

export function removeAgentFile(input: { id: string; destination: string; manifestPath: string }): {
  path: string
  removed: boolean
  kept: boolean
} {
  const manifest = readAgentManifest(input.manifestPath)
  if (!existsSync(input.destination)) {
    delete manifest.agents[input.id]
    writeAgentManifest(input.manifestPath, manifest)
    return { path: input.destination, removed: false, kept: false }
  }
  const existing = readFileSync(input.destination, 'utf8')
  if (manifest.agents[input.id] !== agentHash(existing)) {
    return { path: input.destination, removed: false, kept: true }
  }
  unlinkSync(input.destination)
  delete manifest.agents[input.id]
  writeAgentManifest(input.manifestPath, manifest)
  return { path: input.destination, removed: true, kept: false }
}

export function agentStatus(destination: string, manifestPath: string): string {
  if (!existsSync(destination)) return 'missing'
  const manifest = readAgentManifest(manifestPath)
  const content = readFileSync(destination, 'utf8')
  return manifest.agents.clara === agentHash(content) ? 'installed' : 'modified'
}
