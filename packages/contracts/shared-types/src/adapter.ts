import type { HttpMethod } from './actions.ts'
import type { RelayGrantState } from './grant.ts'

/**
 * Adapter frames travel inside the same sealed WebSocket session as a browser
 * client. The hub sends requests to the adapter and the adapter streams the
 * response back. The relay never parses these payloads.
 */
export type AdapterRequestAction = {
  type: 'adapter.request'
  id: string
  method: HttpMethod
  path: string
  search?: string
  headers?: Record<string, string>
  body?: string
}

export type AdapterAbortAction = {
  type: 'adapter.abort'
  id: string
}

export type AdapterCapabilities = Record<string, unknown>

/** First adapter payload on an enrollment session. */
export type AdapterEnrollAction = {
  type: 'adapter.enroll'
  id?: string
  /** Stable identity that survives uninstall/install. */
  harnessId: string
  kind: string
  label: string
  /** Long-lived E2EE credential id, generated by the adapter. */
  credentialId: string
  /** Base64url 32-byte adapter key. */
  key: string
  adapterVersion: string
  protocolVersion: number
  harnessVersion?: string
  capabilities: AdapterCapabilities
}

export type AdapterAction = AdapterRequestAction | AdapterAbortAction | AdapterEnrollAction

export type AdapterResponseState =
  | {
      type: 'adapter.response'
      id: string
      status: number
      statusText: string
      headers: Record<string, string>
    }
  | { type: 'adapter.chunk'; id: string; data: string }
  | { type: 'adapter.end'; id: string }
  | { type: 'adapter.error'; id: string; message: string; code?: string }

export type AdapterEnrolledState = {
  type: 'adapter.enrolled'
  connectionId: string
  harnessId: string
  label: string
  reconnected: boolean
  /**
   * The first adapter grant. Later connects present it to the relay and
   * receive a refreshed copy in the sealed `ready` action.
   */
  relayGrant?: RelayGrantState
}

export type AdapterState = AdapterResponseState | AdapterEnrolledState

export type AdapterPayload = AdapterAction | AdapterState

export function isAdapterAction(value: unknown): value is AdapterAction {
  if (!isRecord(value) || typeof value.type !== 'string') return false
  return (
    value.type.startsWith('adapter.') &&
    !value.type.startsWith('adapter.response') &&
    !value.type.startsWith('adapter.chunk') &&
    !value.type.startsWith('adapter.end') &&
    !value.type.startsWith('adapter.error') &&
    value.type !== 'adapter.enrolled'
  )
}

export function isAdapterEnrollAction(value: unknown): value is AdapterEnrollAction {
  return isRecord(value) && value.type === 'adapter.enroll' && typeof value.harnessId === 'string'
}

export function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}
