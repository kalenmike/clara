/** Wire protocol version. Bump when a frame shape changes. */
export const PROTOCOL_VERSION = 3

/**
 * The v4 handshake adds ephemeral P-256 ECDH for forward secrecy and a MAC on
 * the hub hello. It is defined alongside v3 until the transport cutover.
 */
export const PROTOCOL_VERSION_V4 = 4

/**
 * Version of the relay route envelope, advertised in `x-clara-relay-version`.
 * It is independent of the E2EE protocol version: envelope v3 adds the grant
 * id the relay verified before it tags a client frame.
 */
export const RELAY_WIRE_VERSION = 3

export type DeviceErrorCode =
  | 'unknown_device'
  | 'revoked_device'
  | 'enrollment_expired'
  | 'enrollment_used'
  | 'enrollment_invalid'
  | 'device_limit'
  | 'invalid_device'
  | 'not_allowed'
  | 'protocol_error'

/** WebSocket subprotocol offered by both clients and the hub. */
export const RELAY_SUBPROTOCOL = 'clara.v1'

export const RELAY_AUTH_PREFIX = 'clara.auth.'
export const RELAY_ROLE_PREFIX = 'clara.role.'

export type RelayRole = 'agent' | 'client'

export type AgentInfo = {
  version: string
  protocol: number
  opencodeVersion?: string
  room?: string
  /** Present when the hub can send Web Push notifications. */
  pushPublicKey?: string
  /** False when an admin disabled client settings sync. Absent means enabled. */
  syncEnabled?: boolean
  /** How often a paired client should check for settings changes. */
  syncIntervalMs?: number
  /** True while the Clara orchestration service is reachable. */
  orchestration?: boolean
}

/**
 * The session id and device id are generated by the client and are safe to
 * expose to the relay. The device id is a stable logical identity, not a
 * hardware fingerprint.
 */
export type SessionHandshake = {
  sid: string
  deviceId?: string
  clientNonce: string
  agentNonce: string
}

export type AuthTokenKind = 'agent' | 'client'
