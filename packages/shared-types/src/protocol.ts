/** Wire protocol version. Bump when a frame shape changes. */
export const PROTOCOL_VERSION = 1

/** WebSocket subprotocol offered by both clients and the home agent. */
export const RELAY_SUBPROTOCOL = 'clara.v1'

export const RELAY_AUTH_PREFIX = 'clara.auth.'
export const RELAY_ROLE_PREFIX = 'clara.role.'

export type RelayRole = 'agent' | 'client'

export type AgentInfo = {
  version: string
  protocol: number
  opencodeVersion?: string
  room?: string
  /** Present when the home agent can send Web Push notifications. */
  pushPublicKey?: string
  /** False when an admin disabled client settings sync. Absent means enabled. */
  syncEnabled?: boolean
  /** How often a paired client should check for settings changes. */
  syncIntervalMs?: number
  /** True while the Clara orchestration service is reachable. */
  orchestration?: boolean
}

/** The session id is generated by the client and is safe to expose to the relay. */
export type SessionHandshake = {
  sid: string
  clientNonce: string
  agentNonce: string
}

export type AuthTokenKind = 'agent' | 'client'
